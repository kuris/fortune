  /**
   * 7. login.html - 로그인 및 내 운세함 대시보드 렌더링
   */
  function renderLoginView() {
    const guestSec = document.getElementById('guest-auth-section');
    const userSec = document.getElementById('user-dashboard-section');
    const googleBtn = document.getElementById('btn-google-login');
    const logoutBtn = document.getElementById('btn-logout');
    const userEmailEl = document.getElementById('user-display-email');
    const userNameEl = document.getElementById('user-display-name');
    const zodiacSelect = document.getElementById('user-favorite-zodiac');
    const starSelect = document.getElementById('user-favorite-star');
    const savePrefsBtn = document.getElementById('btn-save-preferences');
    const historyList = document.getElementById('saved-history-list');
    const savedCountEl = document.getElementById('saved-count');
    const clearHistoryBtn = document.getElementById('btn-clear-history');

    if (!guestSec || !userSec) return;

    if (currentUser) {
      guestSec.style.display = 'none';
      userSec.style.display = 'block';

      const email = currentUser.email || '';
      const name = currentUser.user_metadata?.name || email.split('@')[0] || '사용자';
      if (userEmailEl) userEmailEl.textContent = email;
      if (userNameEl) userNameEl.textContent = name;

      // 즐겨찾기 값 로드
      const prefs = getUserPrefs();
      if (zodiacSelect) zodiacSelect.value = prefs.favoriteZodiac || '';
      if (starSelect) starSelect.value = prefs.favoriteStar || '';

      // 저장된 기록 렌더링
      renderSavedHistory();
    } else {
      guestSec.style.display = 'block';
      userSec.style.display = 'none';
    }

    // 구글 로그인 이벤트 바인딩
    if (googleBtn) {
      googleBtn.onclick = async () => {
        if (!sbClient) {
          showToast("로그인 서비스를 준비 중입니다.");
          return;
        }
        try {
          const redirectUrl = getFortuneRedirectUrl();
          const { error } = await sbClient.auth.signInWithOAuth({
            provider: 'google',
            options: { redirectTo: redirectUrl }
          });
          if (error) throw error;
        } catch (err) {
          console.error(err);
          showToast("구글 로그인 진행 중 오류가 발생했습니다.");
        }
      };
    }

    // 로그아웃 이벤트 바인딩
    if (logoutBtn) {
      logoutBtn.onclick = async () => {
        if (sbClient) {
          await sbClient.auth.signOut();
        }
        currentUser = null;
        showToast("로그아웃되었습니다.");
        renderLoginView();
      };
    }

    // 설정 저장 이벤트
    if (savePrefsBtn) {
      savePrefsBtn.onclick = () => {
        const prefs = {
          favoriteZodiac: zodiacSelect?.value || '',
          favoriteStar: starSelect?.value || ''
        };
        saveUserPrefs(prefs);
        showToast("즐겨찾는 띠와 별자리가 저장되었습니다! ⭐");
      };
    }

    // 히스토리 비우기
    if (clearHistoryBtn) {
      clearHistoryBtn.onclick = () => {
        if (confirm("내 운세함의 저장 기록을 모두 삭제하시겠습니까?")) {
          localStorage.removeItem(STORAGE_KEY_SAVED);
          renderSavedHistory();
          showToast("저장된 기록이 모두 삭제되었습니다.");
        }
      };
    }

    function renderSavedHistory() {
      if (!historyList) return;
      const records = getSavedRecords();
      if (savedCountEl) savedCountEl.textContent = records.length;

      if (records.length === 0) {
        historyList.innerHTML = `
          <div id="empty-history-msg" style="text-align: center; padding: 30px 10px; color: var(--text-muted); font-size: 14px;">
            <div style="font-size: 32px; margin-bottom: 8px;">📂</div>
            아직 저장된 운세 기록이 없습니다.<br>
            오늘의 운세나 타로를 보고 하단의 [💾 내 운세함에 저장하기]를 눌러보세요!
          </div>
        `;
        return;
      }

      historyList.innerHTML = '';
      records.forEach((rec, idx) => {
        const item = document.createElement('div');
        item.className = 'mini-fortune-card';
        item.style.position = 'relative';
        item.innerHTML = `
          <div style="display: flex; justify-content: space-between; align-items: flex-start; margin-bottom: 4px;">
            <a href="${rec.link || '#'}" style="font-family: var(--font-display); font-size: 15px; color: var(--main-color); text-decoration: underline;">
              ${rec.title}
            </a>
            <span style="font-size: 11px; color: var(--text-light);">${rec.date}</span>
          </div>
          <p style="font-size: 13.5px; color: var(--text-main); margin-bottom: 6px;">${rec.summary}</p>
          <div style="display: flex; justify-content: flex-end;">
            <button type="button" class="del-record-btn" data-idx="${idx}" style="font-size: 11px; color: #DC2626; border: none; background: none; cursor: pointer;">삭제</button>
          </div>
        `;
        historyList.appendChild(item);
      });

      // 개별 삭제 이벤트
      historyList.querySelectorAll('.del-record-btn').forEach(btn => {
        btn.addEventListener('click', (e) => {
          const idx = parseInt(btn.getAttribute('data-idx'), 10);
          const currentRecords = getSavedRecords();
          currentRecords.splice(idx, 1);
          localStorage.setItem(STORAGE_KEY_SAVED, JSON.stringify(currentRecords));
          renderSavedHistory();
          showToast("기록이 삭제되었습니다.");
        });
      });
    }
  }

